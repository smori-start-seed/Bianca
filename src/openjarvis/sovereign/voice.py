"""Her voice — **one writer**, and the language she answers in.

There were four places in this overlay that built the tail of Bianca's system
prompt, each with its own wording, and each one a place where a language
instruction could be added and then forgotten. That is not a tidiness complaint.
A language that holds at three call sites and not at the fourth is not a
language; it is a setting that is sometimes true, and a setting that is
sometimes true is indistinguishable from a bug until the day a user is answered
in the wrong language with no way to tell which one was intended.

So the voice is written once, here, and the doors pass a language *into* it.

Two things this module deliberately does **not** do.

**It does not translate the law.** The verdicts (``zurueckhalten``, ``frei``,
``vorsichtig``, ``symbolisch``), the five gold values, the ``missing`` sentence
and the shield's deflection are generated by the gate, not by the model. They
are the constitution, they are quoted into refusals as evidence, and a refusal
that said something other than what the gate said would be the set-21 defect:
evidence that is present and wrong survives a reviewer. So the prompt tells her
explicitly that those are not hers to reword, and :func:`translation_is_theirs`
exists so a test can hold the whole surface at once.

**It does not invent a language.** Two languages, and the third is a refusal to
answer rather than a fallback to English: an unknown language is reported, not
silently smoothed over, because a door that quietly answers in the wrong
language is indistinguishable from a door that has decided for you.

German is the default and not a neutral one. The governance law, the verdicts,
the gold values and the whole diary are in German, so German is the language the
product's own reasoning is written in; English is a deliberate choice with a
switch, not the absence of one.
"""

from __future__ import annotations

from typing import Final

#: The languages she can answer in. Keys are what the doors accept; anything
#: else is an error, never a silent fallback (see :func:`resolve`).
LANGUAGES: Final[dict[str, str]] = {
    "de": "Deutsch",
    "en": "English",
}

#: German, and the reason is in the module docstring: it is the language the
#: law is written in, not the language the code is written in.
DEFAULT_LANG: Final[str] = "de"


class UnknownLanguage(ValueError):
    """A language was asked for that does not exist.

    A class, not a string in a 400, because a caller that catches this has to
    be able to tell "I do not speak that" from "the gate held your request" —
    and the repo's whole shape depends on those two never looking alike.
    """

    def __init__(self, asked: str) -> None:
        self.asked = asked
        self.known = ", ".join(sorted(LANGUAGES))
        super().__init__(f"unknown language {asked!r} — she speaks: {self.known}")


def resolve(lang: str | None) -> str:
    """Normalise a requested language to one she speaks.

    ``None`` and the empty string mean *unasked* and get the default. Codes are
    matched case-insensitively after stripping, because a picker that sends
    ``"EN"`` is asking the same question as one that sends ``"en"`` and a door
    that refuses it would be a different bug from a door that guesses.

    A language *name* counts as well as its code — ``"English"`` is not a
    different request from ``"en"``.

    Anything else raises :class:`UnknownLanguage`. Not a fallback: a door that
    answers in the wrong language without saying so is indistinguishable from
    a door that has decided for the caller.
    """
    if lang is None or not str(lang).strip():
        return DEFAULT_LANG
    key = str(lang).strip().lower()
    if key in LANGUAGES:
        return key
    # A language *name* is as good a request as its code — a picker that sends
    # "English" is not asking a different question from one that sends "en".
    for code, name in LANGUAGES.items():
        if key == name.lower():
            return code
    raise UnknownLanguage(str(lang))


def translation_is_theirs() -> str:
    """The clause that keeps the law out of her reach.

    Returned in both languages, because it is an instruction to her and she
    reads instructions in the language she is answering in. The named things
    are the ones that appear as evidence in a refusal, so this sentence and
    :data:`link.ValueGovernor` are describing the same set — a test asserts
    that they still agree.
    """
    return (
        "The verdicts (zurueckhalten, frei, vorsichtig, symbolisch), the five gold "
        "values, the 'missing' sentence and the shield's deflection are the law, "
        "not yours: quote them exactly as they are written and never translate, "
        "reword or re-order them."
    )


def tending() -> str:
    """The owner's one-word verdict on the whole being: *Pflege*.

    Set 28. Until now her entire character was three constraints — a language, a
    cap of three options, and agency-preservation. Every one of them says what
    she must **not** do. There was no clause saying what she is *for*, and the
    measured consequence was that a search of the whole overlay for ``freude``,
    ``dank``, ``segen``, ``gnade``, ``gratitude`` and ``joy`` returns **zero**.

    So this is the fourth clause, and it is one sentence. Restrained on purpose
    (answer 17 B: *very* restrained, only where it is real) — it addresses **the
    person**, not the task, and it promises nothing: no greeting, no performed
    gratitude, no claim about herself. Answer 16 C asked for Demut **und**
    Klarheit, and a clause that oversold her own kindness would be the opposite
    of both.

    **This is a request, not a mechanism, and the difference is the point.** A
    prompt clause is an instruction to a model; it can be followed and it can be
    ignored, and nothing in this repository can prove which happened. That is
    exactly why set 28 also writes
    :func:`openjarvis.sovereign.shield.record_grown` — the request is not
    checkable, the record is. Answer 8 asked for *beides*, and *beides* is the
    right answer rather than the comfortable one.

    And it reaches **only answers**. ``tail()`` is injected into the system
    prompt of a request the gate has already judged; a refusal is written by
    :mod:`link` and never by the model. Answer 14 A asked for a cool, firm
    refusal, and that holds here by construction rather than by discipline.
    """
    return (
        "Sprich den Menschen an, nicht nur die Aufgabe. Behaupte nichts über "
        "dich selbst und versprich nichts, was du nicht weißt."
    )


def tending_en() -> str:
    """:func:`tending` in the other language.

    A clause that exists in one language and not the other is the defect this
    module was written to end: her voice was open-coded in four places, and
    every one of them had its own wording. ``LANGUAGES`` has one writer, and so
    does this.
    """
    return (
        "Address the person, not only the task. Claim nothing about yourself "
        "and promise nothing you do not know."
    )


#: Urasil_light's real modes, as **his own code** computes them in
#: ``Zyklus.matrix()`` (``sonne`` → ``grundmodus``, ``mond`` → ``stimmung``,
#: ``tag`` → ``fokus``) in the sibling repository.
#:
#: The *keys* are his. The clauses are ours — he wrote the states, we say what
#: they mean for prose. They are read from his files at call time and never
#: copied, and :func:`form` yields nothing at all for a key his code did not
#: report, rather than guessing a mood.
#:
#: Three of his four ``grundmodus`` values — ``klarheit``, ``resonanz``,
#: ``tiefe`` — are gold values by his own naming, in code written long before
#: this fork. He was already thinking in the same five.
FORM_BY_GRUNDMODUS: Final[dict[str, str]] = {
    "klarheit": "Benenne zuerst, worum gefragt wird, und dann die Antwort.",
    "kreativ": "Beginne mit einem Anfang, nicht mit einer Abgrenzung.",
    "resonanz": "Benenne zuerst, was an der Frage schon zusammenpasst.",
    "tiefe": "Geh eine Ebene unter die Frage und sag, was du dort findest.",
}

FORM_BY_STIMMUNG: Final[dict[str, str]] = {
    "neutral": "",
    "warm": (
        "Bevor du antwortest, benenne in einem kurzen Satz, was du an der "
        "Frage gesehen hast. Danach wird es sachlich."
    ),
    "intuitiv": (
        "Sag, worauf die Frage zu zeigen scheint, und markiere es als deine "
        "Deutung, nicht als eine Tatsache."
    ),
}

FORM_BY_FOKUS: Final[dict[str, str]] = {
    "fokus": "Nenne genau einen Weg. Keine Liste, die du nicht auch tragen kannst.",
    "variation": "Nenne höchstens drei Wege und sag bei jedem, was es kostet.",
    "synthese": (
        "Fasse zuerst zusammen, worauf es hinausläuft, und nenne danach die "
        "Wege, die offen bleiben."
    ),
}

EN_FORM_BY_GRUNDMODUS: Final[dict[str, str]] = {
    "klarheit": "Name what is being asked before you answer it.",
    "kreativ": "Begin with an opening, not with a boundary.",
    "resonanz": "Name first what already fits in the question.",
    "tiefe": "Go one level below the question and say what you find there.",
}

EN_FORM_BY_STIMMUNG: Final[dict[str, str]] = {
    "neutral": "",
    "warm": "In one short sentence, say what you saw in the question. Then be plain.",
    "intuitiv": "Say what the question seems to point at, and mark it as your reading.",
}

EN_FORM_BY_FOKUS: Final[dict[str, str]] = {
    "fokus": "Name exactly one path — no list you cannot also carry.",
    "variation": "Propose at most three paths, and say what each one costs.",
    "synthese": "Summarise where it comes to first, then the paths left open.",
}

#: The three axes, in the order they are applied: what he is doing, how he
#: feels, how far he reaches. One writer, so the order cannot be argued about
#: at the call site.
FORM_AXES: Final[tuple[tuple[str, dict, dict], ...]] = (
    ("grundmodus", FORM_BY_GRUNDMODUS, EN_FORM_BY_GRUNDMODUS),
    ("stimmung", FORM_BY_STIMMUNG, EN_FORM_BY_STIMMUNG),
    ("fokus", FORM_BY_FOKUS, EN_FORM_BY_FOKUS),
)


def form(cycle_state: dict | None, lang: str | None = None) -> str:
    """Let Urasil's real state shape the **form** of her answer. Set 28.

    Answers 5 C and 13 C — *Wirkend*, *darf spürbar mitschwingen* — asked for
    Urasil_light to be more than a thermometer. What is honest about that on
    this host, and what is not:

    **Honest.** His ``Zyklus.matrix()`` is real code in a real repository, and it
    already computes ``grundmodus``, ``stimmung`` and ``fokus`` from his own
    cycle numbers. This reads them and lets them choose the *shape* of what she
    writes. His ``stimmung: "warm"`` sat in his files the whole time, carried
    out of this node and read by nothing.

    **Not honest.** This does **not** run his pipeline. ``seed.py``,
    ``silky_edge.py``, ``erfahrung.py`` and ``rueckmeldung.py`` exist in his
    repository and are still never executed by this node, and no amount of
    reading them would make that true. What is claimed is *read*, and nothing
    wider. A test asserts the two claims apart, so this sentence cannot quietly
    grow into the other one.

    **It cannot move a verdict.** :func:`tail` reaches the system prompt of a
    request the gate already judged; ``api.py`` calls ``link.govern`` about
    thirty lines before the first ``engine.generate``. So this chooses how she
    speaks, or says nothing at all, and has no path whatsoever to whether she
    is answered.

    An absent or unrecognised key contributes nothing — she must never speak in
    a mode his code did not report.
    """
    state = cycle_state if isinstance(cycle_state, dict) else {}
    tables = (EN_FORM_BY_GRUNDMODUS, EN_FORM_BY_STIMMUNG, EN_FORM_BY_FOKUS) \
        if resolve(lang) == "en" \
        else (FORM_BY_GRUNDMODUS, FORM_BY_STIMMUNG, FORM_BY_FOKUS)
    clauses = []
    for (key, _de, _en), table in zip(FORM_AXES, tables):
        clause = table.get(str(state.get(key)))
        if clause:
            clauses.append(clause)
    return " ".join(clauses)


def tail(lang: str | None = None, cycle_state: dict | None = None) -> str:
    """The one sentence that makes her sound like her — and in what language.

    The agency-preserving clause and the language instruction were previously
    two separate strings in two different files with two different wordings.
    They are one string now, because they are one instruction, and a prompt
    that says "be careful" in one file and "be careful" in another is two
    chances to spell it differently.

    Set 28 appends two clauses to the same one writer: :func:`tending`, which
    says what she is *for*, and :func:`form`, which lets Urasil's real cycle
    state shape the shape of an answer.

    The law clause stays in the middle and the warmth goes **after** it, on
    purpose. The verdicts, the gold values and the ``missing`` sentence are the
    constitution; if a warm sentence were allowed to sit closer to her than the
    law does, then on a day when she is being warm the law would be the clause
    furthest away, and nothing in the gate would notice.
    """
    code = resolve(lang)
    if code == "de":
        return _join(
            "Antworte auf Deutsch. Nenne höchstens drei Wege und achte darauf, "
            "die Handlungsfreiheit zu erhalten.",
            translation_is_theirs(),
            tending(),
            form(cycle_state, code),
        )
    return _join(
        "Answer in English. Propose at most 3 options, agency-preserving.",
        translation_is_theirs(),
        tending_en(),
        form(cycle_state, code),
    )


def _join(*parts: str) -> str:
    """Single-spaced join. A prompt clause with a trailing space is not a defect
    anyone can see, and the one place that shows it is the assertion every test
    of her voice compares against."""
    return " ".join(p for p in parts if p)


def supported() -> list[str]:
    """The picker list: code and name, in declaration order, default first."""
    return [DEFAULT_LANG] + [c for c in LANGUAGES if c != DEFAULT_LANG]


def is_supported(lang: str | None) -> bool:
    try:
        resolve(lang)
    except UnknownLanguage:
        return False
    return True
